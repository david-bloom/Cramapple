"""Generate the app's figure catalogue from specs.json.

`src/lib/figures/catalogue.ts` in `david-bloom/ap-prep-blueprint` is a TEST
FIXTURE and the local /dev-figures harness; production reads `app.figures`.
It is generated rather than hand-maintained, because a catalogue that has
drifted from specs.json looks exactly like one that has not.

Run `export_for_parity.py` first; this reads its `out/parity/specs.json`.

    python3 -I scripts/lane-a-pilot/build_catalogue_ts.py \
        --out ../ap-prep-blueprint/src/lib/figures/catalogue.ts
"""
from __future__ import annotations

import argparse, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))

HEADER = """// Lane A and Lane B figure catalogue - TEST FIXTURE ONLY.
//
// Production no longer reads this. Figures live in app.figures, joined through
// app.figure_uses, and reach the client via get_topic_point_guides. Nothing
// outside src/lib/__tests__ and the local dev-figures harness imports it, and
// nothing should: a bundled fallback would serve stale content and look
// exactly like working.
//
// GENERATED by scripts/lane-a-pilot/build_catalogue_ts.py in the governance
// repo. Do not edit by hand: regenerate it, so this file cannot drift from
// specs.json. Every figure here is byte-identical between the python reference
// renderer and this one at all three layouts, proved by tests/figure-parity.ts.

import type { FigureSpec } from "./types";

export const FIGURES: Record<string, FigureSpec> = {
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--specs", default=os.path.join(HERE, "out", "parity", "specs.json"))
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    specs = json.load(open(args.specs, encoding="utf-8"))
    parts = []
    for f in specs:
        blob = json.dumps(f, indent=2, ensure_ascii=False)
        blob = "\n".join("  " + ln for ln in blob.split("\n")).lstrip()
        parts.append(f"  {json.dumps(f['figureId'])}: {blob}")
    out = HEADER + ",\n".join(parts) + ",\n};\n"
    open(args.out, "w", encoding="utf-8").write(out)
    print(f"{len(specs)} figures -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
